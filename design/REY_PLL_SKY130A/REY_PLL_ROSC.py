"""REY_PLL_ROSC: the layout, as a cicpy sidecar.

The circuit (work/xsch/REY_PLL_ROSC.spice, generated by py/gen_rosc.py):

  * seven ring stages. Stage k is xip<k>/xin<k>, the inverter, with its
    PMOS source on VS<k>; VS<k> is fed by the fixed mirror xmpfa/xmpfb<k>
    and by the tunable mirror xmpca<k> through the VCTRL device xmpv<k>
    (NC<k> between them). The ring nets N<k> are the only nets between
    stages.
  * the Vgs/R bias: PMOS diode xmpd<3:0> on VBP, mirror xmpb<3:0> into
    xmn1 (VX), LVT follower xmn2<3:0> from VX to VG, R from VG to VSS
  * startup xms1 (PMOS), xms2<1:0>, xms3, and the trim switches xst0..2
  * the trim resistor, REYATR_RES_36C2F0 units: xrf0, xrf1, xrf2<1:0>,
    xrt0<1:0>, xrt1, xrt2a, xrt2b
  * the output buffer, REYTR_IVX1 xo0 and REYTR_IVX4 xo1

Floorplan, two rows (an nmos column abutted to a pmos one breaks the
well rules, see REY_LDO):

    top (n-well):  p_diode p_mirb p_st0 .. p_st6
    bottom:        r_trim r_fix n_sw n_su n_bias n_ring_a n_ring_b dig

Each p_st<k> column holds one stage's PMOS, bottom to top: the inverter
PMOS (its drain N<k> nearest the nmos row), the VCTRL device, the tunable
mirror and the two fixed mirrors. VS<k> and NC<k> stay inside the column.
The seven inverter NMOS share two columns; the ring nets cross the
channel between the rows. No column is taller than five devices.

This first version is placement only.
"""
import logging

from cicpy.sidecar import SidecarCell, Stack

log = logging.getLogger("REY_PLL_ROSC")

NSTAGE = 7


class _P(Stack):
    """A PMOS column. Every VDD_1V8 pin in it is a source or a bulk, and
    the guard ring ties those beside each device, so VDD_1V8 is not for
    the router."""
    group = "pmos"
    fill = False
    blocked = [("VDD_1V8", "sources and bulks; the guard carries it")]


class _N(Stack):
    """An NMOS column, VSS the same way."""
    group = "nmos"
    fill = False
    blocked = [("VSS", "sources and bulks; the guard carries it")]


class REY_PLL_ROSC(SidecarCell):

    #- Every column is kept at five devices or fewer, so the two rows come
    #- out about as tall as a ring stage column

    class p_diode(_P):
        """The PMOS diode on VBP, four units."""
        match = r'^xmpd<\d+>$'
        order = [r'xmpd<\d+>']

    class p_mirb(_P):
        """The mirror into MN1 (VX), and the startup PMOS on top."""
        match = r'^(xmpb<\d+>|xms1)$'
        order = [r'xmpb<\d+>', 'xms1']

    class n_bias(_N):
        """MN1 and the LVT follower MN2 (VG on MN1's gate and MN2's
        sources)."""
        match = r'^(xmn1|xmn2<\d+>)$'
        order = ['xmn1', r'xmn2<\d+>']

    class n_su(_N):
        """Startup NMOS, NCH_4C1F2."""
        match = r'^(xms2<\d+>|xms3)$'
        order = [r'xms2<\d+>', 'xms3']

    class n_sw(_N):
        """The trim switches, NCH_4C1F2, bit 2 (nearest VSS) at the
        bottom."""
        match = r'^xst\d$'
        order = ['xst2', 'xst1', 'xst0']

    class r_trim(Stack):
        """The switched half of R, VSS at the bottom up to RT0."""
        match = r'^(xrt0<\d+>|xrt1|xrt2[ab])$'
        group = "res"
        fill = False
        order = ['xrt2b', 'xrt2a', 'xrt1', r'xrt0<\d+>']

    class r_fix(Stack):
        """The fixed half of R, RT0 at the bottom up to VG."""
        match = r'^(xrf[01]|xrf2<\d+>)$'
        group = "res"
        fill = False
        order = [r'xrf2<\d+>', 'xrf1', 'xrf0']

    class n_ring_a(_N):
        """Inverter NMOS of stages 0 to 3."""
        match = r'^xin<[0-3]>$'
        order = ['xin<0>', 'xin<1>', 'xin<2>', 'xin<3>']

    class n_ring_b(_N):
        """Inverter NMOS of stages 4 to 6."""
        match = r'^xin<[4-6]>$'
        order = ['xin<4>', 'xin<5>', 'xin<6>']

    class dig(Stack):
        """The output buffer, rey_tr standard cells."""
        match = r'^(xo0|xo1)$'
        group = "dig"
        fill = False
        order = ['xo0', 'xo1']

    supplies = [
        {"net": "VDD_1V8", "ring": "t", "strap": "top", "pin_strap": True},
        {"net": "VSS", "ring": "b", "strap": "bottom", "pin_strap": True},
    ]

    channel = 4
    routes = []


#- one PMOS column per ring stage
for _k in range(NSTAGE):
    _p = type(f"p_st{_k}", (_P,), dict(
        __doc__=f"Stage {_k}: inverter PMOS, VCTRL device, tunable and "
                f"fixed mirrors, bottom to top.",
        match=rf'^(xip<{_k}>|xmpv<{_k}>|xmpca<{_k}>|xmpf[ab]<{_k}>)$',
        order=[f'xip<{_k}>', f'xmpv<{_k}>', f'xmpca<{_k}>',
               f'xmpfa<{_k}>', f'xmpfb<{_k}>']))
    setattr(REY_PLL_ROSC, f"p_st{_k}", _p)

_C = REY_PLL_ROSC
REY_PLL_ROSC.rows = [
    [_C.r_trim, _C.r_fix, _C.n_sw, _C.n_su, _C.n_bias,
     _C.n_ring_a, _C.n_ring_b, _C.dig],
    [_C.p_diode, _C.p_mirb]
    + [getattr(_C, f"p_st{k}") for k in range(NSTAGE)],
]
